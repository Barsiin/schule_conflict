public class Schule
{
        private String name;
        private int alter;
        private boolean matura;
        private boolean abendschule;
        
       public String getName()
       {
        return name;
       }
    
       public int getAlter()
       {
           return alter;
       }
       
       public boolean getMatura()
       {
           return matura;
       }
       
       public boolean getAbendschule()
       {
           return abendschule;
       }
       
}